def get_bot_reply(user_text: str, online_names: list[str]) -> tuple[str, list[str]]:
    """Возвращает (текст_ответа, список_быстрых_кнопок)."""
    lower = user_text.strip().lower()

    if any(w in lower for w in ("кто онлайн", "онлайн", "пользовател", "люди")):
        count = len(online_names)
        if count == 0:
            return "Сейчас на сайте пока никого нет.", QUICK_BUTTONS
        names_preview = ", ".join(online_names[:15])
        extra = f" и ещё {count - 15}" if count > 15 else ""
        return (
            f"Сейчас на сайте онлайн ({count}): {names_preview}{extra}.\n"
            "Нажмите на любое имя в левом списке, чтобы написать в личку!",
            ["Правила чата", "Шутка", "Помощь"],
        )

    if any(w in lower for w in ("шутк", "анекдот", "рассмеш")):
        return random.choice(JOKES), ["Ещё шутку", "Бросить кубик", "Кто онлайн?"]

    if any(w in lower for w in ("кубик", "/roll", "кости")):
        num = random.randint(1, 6)
        return f"🎲 Выпало: {num}", ["Бросить кубик", "Орёл или решка", "Помощь"]

    if any(w in lower for w in ("орёл", "орел", "решк", "монет", "/flip")):
        side = random.choice(["Орёл", "Решка"])
        return f"🪙 Выпало: {side}", ["Орёл или решка", "Бросить кубик", "Помощь"]

    if any(w in lower for w in ("время", "который час", "/time", "дата")):
        now = datetime.datetime.now()
        return (
            f"⏰ Сейчас {now.strftime('%H:%M:%S')} ({now.strftime('%d.%m.%Y')}).",
            ["Кто онлайн?", "Шутка", "Помощь"],
        )

    for keywords, reply in CANNED_RULES:
        if any(kw in lower for kw in keywords):
            return reply, QUICK_BUTTONS

    return (
        "Я бот с заготовленными ответами и пока не знаю такую фразу 🙂\n"
        "Выберите одну из кнопок ниже или напишите «Помощь».",
        QUICK_BUTTONS,
    )
